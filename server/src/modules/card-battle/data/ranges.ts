import type { RangeCode, RangePattern } from '../../../../../shared/cb/types';

/**
 * 공격 범위 10종 (기준서 9번).
 * 사용자의 현재 칸이 가운데(1,1)인 3×3 절대 좌표 패턴이다.
 * 1P/2P 에 따라 좌우 반전하지 않는다 — 그래서 10종 전부 좌우 대칭으로 설계돼 있다 (기준서 8번).
 */
export const RANGES: Readonly<Record<RangeCode, RangePattern>> = {
  H: [[0, 0, 0], [1, 1, 1], [0, 0, 0]],
  V: [[0, 1, 0], [0, 1, 0], [0, 1, 0]],
  C: [[0, 1, 0], [1, 1, 1], [0, 1, 0]],
  X: [[1, 0, 1], [0, 1, 0], [1, 0, 1]],
  T: [[1, 1, 1], [0, 0, 0], [0, 0, 0]],
  B: [[0, 0, 0], [0, 0, 0], [1, 1, 1]],
  U: [[1, 1, 1], [1, 1, 1], [0, 0, 0]],
  D: [[0, 0, 0], [1, 1, 1], [1, 1, 1]],
  O: [[1, 1, 1], [0, 0, 0], [1, 1, 1]],
  A: [[1, 1, 1], [1, 1, 1], [1, 1, 1]],
};

/** 좌우 대칭인지 — 기준서 8번의 전제를 테스트가 직접 확인할 수 있게 열어 둔다. */
export function isLeftRightSymmetric(p: RangePattern): boolean {
  return p.every((row) => row[0] === row[2]);
}
